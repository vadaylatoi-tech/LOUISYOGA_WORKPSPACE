// Real Louis Yoga product avatar, optional label under it; `line` draws a pink guide over the centre line.
const MatCard: React.FC<{ src: string; label?: string; x: number; y: number; w: number; h: number; at: number; active?: boolean; line?: number }> = ({ src, label, x, y, w, h, at, active, line }) => {
  const frame = useCurrentFrame();
  if (frame < f(at)) return null;
  const p = spring({ frame: frame - f(at), fps: FPS, config: { damping: 12, stiffness: 180 } });
  const draw = line === undefined ? 0 : interpolate(frame, [f(line), f(line) + 10], [0, 1], { ...clamp, easing: Easing.out(Easing.cubic) });
  return (
    <div style={{ position: "absolute", left: x, top: y, width: w, transform: `translateY(${(1 - p) * 60}px) scale(${0.7 + 0.3 * p})`, opacity: Math.min(1, p * 2) }}>
      <div style={{ position: "relative", width: w, height: h, borderRadius: 12, overflow: "hidden", background: "#F2F0EC", border: `3px solid ${active ? C.accent : "rgba(255,255,255,0.85)"}`, boxShadow: active ? "0 0 26px rgba(255,90,174,0.55)" : "0 8px 18px rgba(0,0,0,0.45)" }}>
        <Img src={staticFile(src)} style={{ width: w, height: h, objectFit: "cover" }} />
        {draw > 0 && <div style={{ position: "absolute", left: w / 2 - 4, top: h * 0.06, width: 8, height: h * 0.88 * draw, borderRadius: 4, background: C.accent, boxShadow: `0 0 14px ${C.accent}` }} />}
      </div>
      {label && <div style={{ ...font(900, 28), color: active ? C.accent : C.white, textAlign: "center", marginTop: 8, letterSpacing: 0 }}>{label}</div>}
    </div>
  );
};

