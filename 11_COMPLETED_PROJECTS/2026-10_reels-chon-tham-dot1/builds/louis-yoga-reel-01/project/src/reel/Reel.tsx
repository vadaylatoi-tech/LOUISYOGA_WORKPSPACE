// Small product card (real Louis Yoga avatar) with a name under it.
const MatCard: React.FC<{ src: string; label?: string; x: number; y: number; w: number; h: number; at: number; active?: boolean }> = ({ src, label, x, y, w, h, at, active }) => {
  const frame = useCurrentFrame();
  if (frame < f(at)) return null;
  const p = spring({ frame: frame - f(at), fps: FPS, config: { damping: 12, stiffness: 180 } });
  return (
    <div style={{ position: "absolute", left: x, top: y, width: w, transform: `translateY(${(1 - p) * 60}px) scale(${0.7 + 0.3 * p})`, opacity: Math.min(1, p * 2) }}>
      <div style={{ width: w, height: h, borderRadius: 12, overflow: "hidden", background: "#F2F0EC", border: `3px solid ${active ? C.accent : "rgba(255,255,255,0.85)"}`, boxShadow: active ? "0 0 26px rgba(255,90,174,0.55)" : "0 8px 18px rgba(0,0,0,0.45)" }}>
        <Img src={staticFile(src)} style={{ width: w, height: h, objectFit: "cover" }} />
      </div>
      {label && <div style={{ ...font(900, 24), color: C.white, textAlign: "center", marginTop: 8, letterSpacing: 0 }}>{label}</div>}
    </div>
  );
};

